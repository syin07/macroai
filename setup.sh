#!/usr/bin/env bash
# Tells your coding CLI (Claude Code or Codex) who you are on this project.
# Usage: ./setup.sh [sandy|ken]   (asks if no name is given; safe to re-run)
set -euo pipefail

cd "$(dirname "$0")"

role="${1:-}"
if [[ -z "$role" ]]; then
  read -r -p "Who are you? [sandy/ken]: " role
fi
role="$(echo "$role" | tr '[:upper:]' '[:lower:]')"

case "$role" in
  sandy)
    name="Sandy"
    partner="Ken"
    title="Backend & AI pipeline"
    plan="docs/plans/sandy-backend-ai.md"
    partner_plan="docs/plans/ken-frontend.md"
    owns='- `src/app/api/**` (all route handlers)
- `src/lib/ai/**`, `src/lib/nutrition/**`, `src/lib/database/**`, `src/lib/memory/**`
- `src/lib/auth/**`, `src/proxy.ts` (Next 16's middleware), `src/app/auth/**`
- `src/lib/validation/**`, `src/types/**` (contract changes need Ken'"'"'s review)
- `supabase/**` (migrations, RLS, seed) and `tests/eval/**` (model bake-off)'
    hands_off='- Pages, layouts, components, hooks, styles, `src/lib/api/**`, `src/mocks/**`, `public/**` belong to Ken.'
    focus='- Security first: every route authenticates, checks approval, validates with Zod, and uses the session user ID.
- Correctness of nutrition math and RLS matters more than speed. Write tests for both.
- When a checkpoint (H1–H8 in shared-contracts §5) lands, remind Sandy to tell Ken.'
    ;;
  ken)
    name="Ken"
    partner="Sandy"
    title="Frontend"
    plan="docs/plans/ken-frontend.md"
    partner_plan="docs/plans/sandy-backend-ai.md"
    owns='- `src/app/(auth)/**`, `src/app/(app)/**`, `src/app/layout.tsx`, `src/app/manifest.ts`
- `src/components/**`, `src/hooks/**`
- `src/lib/api/**` (typed fetch wrappers + mock switch), `src/lib/image/**`
- `src/mocks/**`, `public/**`, styles and Tailwind config'
    hands_off='- `src/app/api/**`, `src/lib/{ai,nutrition,database,auth,validation,memory}/**`, `src/types/**`, `src/proxy.ts`, `src/app/auth/**`, `supabase/**`, `tests/eval/**` belong to Sandy. You may import from them, not edit them.'
    focus='- Mobile first (375 px), both light and dark themes, every async action has loading, error (keeping input), and retry states.
- Build against mocks (`NEXT_PUBLIC_USE_MOCKS=1`) until the matching checkpoint (H1–H8 in shared-contracts §5) lands; never block on the backend.
- Import types from `src/types/api.ts`; never redefine them.'
    ;;
  *)
    echo "Unknown name '$role'. Use: ./setup.sh sandy  or  ./setup.sh ken" >&2
    exit 1
    ;;
esac

# Prints the role section. $1 is "claude" (inline the plan with @imports)
# or "codex" (Codex has no imports, so tell it to read the files).
role_section() {
  cat <<EOF
You are pairing with **$name**, who owns the **$title** on MacroAI. $partner owns the other half.

EOF
  if [[ "$1" == "claude" ]]; then
    cat <<EOF
### $name's plan (work through it in order)

@$plan

### Shared contracts (API shapes, ownership, checkpoints)

@docs/plans/shared-contracts.md
EOF
  else
    cat <<EOF
### Read these first

At the start of every session, before answering or editing anything, read:

1. \`$plan\`: $name's step-by-step plan. Work through it in order.
2. \`docs/plans/shared-contracts.md\`: API shapes, file ownership, and checkpoints.

Read \`docs/PRD.md\` sections as a step needs them.
EOF
  fi
  cat <<EOF

### $name owns

$owns

### Hands off

$hands_off

If a task needs a change there, stop and draft a message for $name to send to $partner instead. $partner's plan is in \`$partner_plan\`, for reference.

### Focus

$focus
EOF
}

header="<!-- Generated by setup.sh for $name. Not committed; re-run ./setup.sh after changing roles or pulling changes to AGENTS.md. -->"

# Claude Code: CLAUDE.md imports AGENTS.md and this file.
mkdir -p .claude
{ echo "$header"; echo; role_section claude; } > .claude/role.md

# Codex: AGENTS.override.md replaces AGENTS.md in this folder, so it
# carries the shared rules plus the role section.
{ echo "$header"; echo; cat AGENTS.md; echo; echo "## Your developer"; echo; role_section codex; } > AGENTS.override.md

# Keep per-person and secret files out of git.
touch .gitignore
for entry in ".claude/role.md" "AGENTS.override.md" ".claude/settings.local.json" ".env*.local" ".env" ".vercel" "node_modules/" ".next/" ".DS_Store"; do
  grep -qxF "$entry" .gitignore || echo "$entry" >> .gitignore
done

# Prerequisite check (warn only; installs nothing).
warn() { echo "  ! $*"; }
echo "Checking tools:"
command -v git >/dev/null || warn "git not found"
if command -v node >/dev/null; then
  major="$(node -p 'process.versions.node.split(".")[0]')"
  [[ "$major" -ge 20 ]] || warn "Node $major found; use Node 20 or newer"
else
  warn "Node.js not found; install Node 20+"
fi
command -v npm >/dev/null || warn "npm not found"
if [[ "$role" == "sandy" ]]; then
  command -v supabase >/dev/null || warn "Supabase CLI not found (brew install supabase/tap/supabase)"
fi
if [[ -f .env.example && ! -f .env.local ]]; then
  cp .env.example .env.local
  echo "  Created .env.local from .env.example; fill in the values."
fi

echo
echo "Done. Your CLI now knows you're $name ($title)."
echo "  Context files: .claude/role.md (Claude Code) and AGENTS.override.md (Codex)"
echo "  Your plan:    $plan"
echo "Start a session in this folder and ask: \"What's my next step?\""
